-- 上门服务项目表
CREATE TABLE service_item (
    id                BIGINT AUTO_INCREMENT PRIMARY KEY,
    category_id       BIGINT       NOT NULL COMMENT '分类ID',
    item_name         VARCHAR(64)  NOT NULL COMMENT '服务名称',
    item_no           VARCHAR(16)  COMMENT '服务编号',
    description       TEXT         COMMENT '服务描述',
    cover_url         VARCHAR(255) COMMENT '封面图URL',
    service_duration  INT          COMMENT '服务时长(分钟)',
    base_price        DECIMAL(8,2) NOT NULL COMMENT '基础价格',
    traffic_fee       DECIMAL(8,2) DEFAULT 0 COMMENT '交通费',
    suitable_people   TEXT         COMMENT '适用人群',
    contraindications TEXT         COMMENT '禁忌症',
    risk_notice       TEXT         COMMENT '风险告知书',
    notes             VARCHAR(1024) COMMENT '服务须知',
    sort_order        INT DEFAULT 0 COMMENT '排序',
    status            TINYINT DEFAULT 1 COMMENT '0:下架 1:上架',
    created_at        DATETIME DEFAULT CURRENT_TIMESTAMP,
    updated_at        DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    INDEX idx_category (category_id)
) COMMENT '上门服务项目';

